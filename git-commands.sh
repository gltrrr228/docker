# Commit commands
git add .         # Добавить индексацию
git commit -m "Discription"      # Сделать коммит
git push    # Отправить изменения в отдаленный репозиторий

git pull    # Слить изменения из отдаленного репозитория

# Branches commands
git branch -m old-branch new-branch  # Создать новую ветку
git switch   # Перейти в новую ветку



